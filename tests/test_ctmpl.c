static void test_features(void)
{
    static const char *src = "#include \"page.h\"\n"
                             "\n"
                             "component loop(size_t n) {\n"
                             "  <ul>\n"
                             "  for size_t i = 0; i < n; i++ {\n"
                             "    <li>{ tpl_int(out, i) }</li>\n"
                             "  }\n"
                             "  </ul>\n"
                             "}\n"
                             "\n"
                             "component raw_demo(const char *html) {\n"
                             "  @raw(html)\n"
                             "}\n"
                             "\n"
                             "component quote_demo(const char *v) {\n"
                             "  <p title=\"static and { v } mixed\">x</p>\n"
                             "}\n";
    char *h = NULL;
    char *c = NULL;
    CtmplError err;
    CHECK(run(src, &h, &c, &err) == 0);

    /* #-line lands in the .h, verbatim */
    IN_H("#include \"page.h\"");
    NOT_IN_C("#include \"page.h\"");

    /* for loop */
    IN_C("for (size_t i = 0; i < n; i++) {");
    IN_C("tpl_esc(out, (tpl_int(out, i)));");

    /* @raw */
    IN_C("tpl_raw(out, (html));");

    /* interpolation inside a quoted attribute value */
    IN_C("title=\\\"static and \");");
    IN_C("tpl_attr(out, (v));");
    free_run(h, c);
}

static void test_children(void)
{
    static const char *src = "component wrap(TplChildren *children) {\n"
                             "  <div>{ children... }</div>\n"
                             "}\n"
                             "\n"
                             "component show(const char *msg) {\n"
                             "  @wrap() {\n"
                             "    <p>{ msg }</p>\n"
                             "  }\n"
                             "}\n";
    char *h = NULL;
    char *c = NULL;
    CtmplError err;
    CHECK(run(src, &h, &c, &err) == 0);

    /* children render guard */
    IN_C("if (children != NULL && children->fn != NULL) {");
    IN_C("children->fn(out, children->data);");

    /* parameter capture: the lambda takes the ENCLOSING component's
     * parameter — the block references msg directly, no with() */
    IN_C("static void tpl__block_1(TplOut *out, const char *msg)");
    IN_C("tpl_esc(out, (msg));");

    /* the adapter matches TplChildren.fn and forwards the void * */
    IN_C("static void tpl__block_1_adapter(TplOut *out, void *tpl_data)");
    IN_C("tpl__block_1(out, tpl_data);");

    /* lambda + adapter are emitted before the component that uses them */
    const char *lambda = strstr(c, "static void tpl__block_1");
    const char *show = strstr(c, "void tpl_show(");
    CHECK(lambda != NULL);
    CHECK(show != NULL);
    CHECK(lambda < show);

    /* the call site binds the captured parameter through data */
    IN_C("TplChildren tpl_children = {tpl__block_1_adapter, "
         "(void *)(msg)};");
    IN_C("tpl_wrap(out, &tpl_children);");
    free_run(h, c);
}

static void test_children_with(void)
{
    /* explicit data binding: the block sees tpl_data (void *), the
     * call binds an arbitrary expression via with (...) */
    static const char *src =
        "component wrap(TplChildren *children, size_t a, size_t b) {\n"
        "  <div>{ children... }</div>\n"
        "}\n"
        "\n"
        "component show(const char *msgs[2]) {\n"
        "  @wrap(1, 2) with (msgs[0]) {\n"
        "    <p>{ (const char *)tpl_data }</p>\n"
        "  }\n"
        "}\n";
    char *h = NULL;
    char *c = NULL;
    CtmplError err;
    CHECK(run(src, &h, &c, &err) == 0);
    /* multi-param components cannot capture: untyped lambda */
    IN_C("static void tpl__block_1(TplOut *out, void *tpl_data)");
    IN_C("TplChildren tpl_children = {tpl__block_1, "
         "(void *)(msgs[0])};");
    IN_C("tpl_wrap(out, 1, 2, &tpl_children);");
    free_run(h, c);
}

static void test_fragment_once(void)
{
    static const char *src = "once note_style\n"
                             "\n"
                             "component feature_note(void) {\n"
                             "  @once(note_style) {\n"
                             "    <style>.note { color: #666; }</style>\n"
                             "  }\n"
                             "  <p class=\"note\">x</p>\n"
                             "}\n"
                             "\n"
                             "component home(const Page *p) {\n"
                             "  @fragment(\"links\") {\n"
                             "    <li>{ tpl_int(out, p->n) }</li>\n"
                             "  }\n"
                             "}\n";
    char *h = NULL;
    char *c = NULL;
    CtmplError err;
    CHECK(run(src, &h, &c, &err) == 0);

    /* once declaration: file-static handle with debug name */
    IN_C("static TplOnce note_style = {.name = \"note_style\"};");

    /* @once: wrapped in tpl_once_begin, block INLINE (no lambda) */
    IN_C("if (tpl_once_begin(out, &(note_style))) {");
    IN_C("<style>.note { color: #666; }</style>");
    NOT_IN_C("tpl__block_");

    /* @fragment: begin/end markers, body inline */
    IN_C("tpl_frag_begin(out, (\"links\"));");
    IN_C("tpl_frag_end(out);");
    IN_C("tpl_esc(out, (tpl_int(out, p->n)));");

    /* handle names do not leak into the .h */
    CHECK(strstr(h, "note_style") == NULL);
    free_run(h, c);
}

static void test_fragment_once_errors(void)
{
    /* @once without a block */
    expect_error("once h\n"
                 "component t(void) {\n"
                 "  @once(h)\n"
                 "}\n",
                 "@once requires a child block", 3);

    /* @fragment without an argument */
    expect_error("component t(void) {\n"
                 "  @fragment { <p>x</p> }\n"
                 "}\n",
                 "@fragment expects an argument", 2);

    /* with (...) on a builtin */
    expect_error("component t(void) {\n"
                 "  @fragment(\"x\") with (y) { <p>x</p> }\n"
                 "}\n",
                 "with (...) is not valid for @fragment", 2);

    /* component names may not shadow builtins */
    expect_error("component fragment(void) {\n"
                 "  <p>x</p>\n"
                 "}\n",
                 "collides with the runtime", 1);
    expect_error("component once(void) {\n"
                 "  <p>x</p>\n"
                 "}\n",
                 "collides with the runtime", 1);

    /* duplicate once declaration */
    expect_error("once h\n"
                 "once h\n"
                 "component t(void) {\n"
                 "  <p>x</p>\n"
                 "}\n",
                 "already declared", 2);
}

static void test_raw_text_elements(void)
{
    static const char *src =
        "component page(void) {\n"
        "  <script>if (x) { var y = 1 > 0; }</script>\n"
        "  <style>a { color: red; } b { color: blue; }</style>\n"
        "  <!-- comment with > inside -->\n"
        "}\n";
    char *h = NULL;
    char *c = NULL;
    CtmplError err;
    CHECK(run(src, &h, &c, &err) == 0);
    /* braces pass through uninterpreted in raw-text elements */
    IN_C("if (x) { var y = 1 > 0; }");
    IN_C("a { color: red; } b { color: blue; }");
    IN_C("<!-- comment with > inside -->");
    free_run(h, c);

    /* missing close tag for a raw-text element */
    CHECK(run("component page(void) {\n"
              "  <script>never closed\n"
              "}\n",
              &h, &c, &err) == -1);
    CHECK(strstr(err.message, "missing </script>") != NULL);
    free_run(h, c);
}

static void test_keyword_text_escaping(void)
{
    /* Text runs starting with if/for are statements — the docs say
     * to use expressions for literal text. */
    char *h = NULL;
    char *c = NULL;
    CtmplError err;
    CHECK(run("component t(void) {\n"
              "  { \"for a day\" }\n"
              "}\n",
              &h, &c, &err) == 0);
    IN_C("tpl_esc(out, (\"for a day\"));");
    free_run(h, c);

    /* a text run starting with "for" INSIDE an element body is
     * also an error — templ rejects the same thing (its docs use
     * <p>if a tree fell</p> as the canonical mistake) */
    CtmplError err2;
    CHECK(run("component t(void) {\n"
              "  <p>for a day</p>\n"
              "}\n",
              &h, &c, &err2) == -1);
    CHECK(strstr(err2.message, "unbalanced") != NULL);
    free_run(h, c);
}


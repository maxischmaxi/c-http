/* Golden + error tests for the ctmpl generator.
 *
 * The generator API is exercised in-process (open_memstream), so the
 * tests check the exact generated text without touching the file
 * system. Exact goldens cover the core shapes; the longer feature
 * tests use substring checks to stay robust against cosmetic output
 * changes.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "ctmpl.h"
#include "test.h"

/* Compiles src; returns 0 on success (h/c receive the output) or -1
 * (err receives the error). Always NUL-terminates the outputs. */
static int run(const char *src, char **h, char **c, CtmplError *err)
{
    *h = NULL; /* never leave dangling pointers behind on failure */
    *c = NULL;
    FILE *fh = NULL;
    FILE *fc = NULL;
    char *bh = NULL;
    char *bc = NULL;
    size_t zh = 0;
    size_t zc = 0;

    fh = open_memstream(&bh, &zh);
    fc = open_memstream(&bc, &zc);
    if (fh == NULL || fc == NULL) {
        fclose(fh);
        fclose(fc);
        free(bh);
        free(bc);
        return -1;
    }
    int rc = ctmpl_compile(src, strlen(src), "test.thtml", fh, fc, err);
    fclose(fh);
    fclose(fc);
    if (rc != 0) {
        free(bh);
        free(bc);
        return -1;
    }
    *h = bh;
    *c = bc;
    return 0;
}

static void free_run(char *h, char *c)
{
    free(h);
    free(c);
}

/* CHECK that `needle` occurs in the generated code. */
#define IN_C(needle)     CHECK(strstr(c, (needle)) != NULL)
#define IN_H(needle)     CHECK(strstr(h, (needle)) != NULL)
#define NOT_IN_C(needle) CHECK(strstr(c, (needle)) == NULL)

static void expect_error(const char *src, const char *needle, size_t line);


static void test_attr_contexts(void)
{
    static const char *src =
        "component a(const Item *it) {\n"
        "  <a href={ tpl_url(out, it->url) } src={ tpl_safe_url(it->u2) }\n"
        "    data-src={ it->x } class=\"c\">x</a>\n"
        "  <p style={ tpl_css(out, it->css) }>y</p>\n"
        "  <p title=\"static { it->t } mixed\">z</p>\n"
        "}\n";
    char *h = NULL;
    char *c = NULL;
    CtmplError err;
    CHECK(run(src, &h, &c, &err) == 0);

    /* URL attributes: TplUrl-forcing writer */
    IN_C("tpl_attr_url(out, (tpl_url(out, it->url)));");
    IN_C("tpl_attr_url(out, (tpl_safe_url(it->u2)));");

    /* data-* attributes are plain attribute context */
    IN_C("tpl_attr(out, (it->x));");

    /* style: the CSS sanitizer context */
    IN_C("tpl_attr_css(out, (tpl_css(out, it->css)));");

    /* quoted-attribute interps keep their attribute context */
    IN_C("tpl_attr(out, (it->t));");

    /* constant attribute values are untouched */
    IN_C("class=\\\"c\\\"");
    free_run(h, c);
}

static void test_attr_context_errors(void)
{
    /* on* attributes reject expressions (templ's injection rule) */
    expect_error("component t(const char *js) {\n"
                 "  <button onclick={ js }>x</button>\n"
                 "}\n",
                 "expressions in 'onclick' attributes are not supported", 2);

    /* hx-on:* is treated the same */
    expect_error("component t(const char *js) {\n"
                 "  <button hx-on:click={ js }>x</button>\n"
                 "}\n",
                 "expressions in 'hx-on:click' attributes", 2);

    /* constant on* attributes are fine */
    char *h = NULL;
    char *c = NULL;
    CtmplError err;
    CHECK(run("component t(void) {\n"
              "  <button onclick=\"alert(1)\">x</button>\n"
              "}\n",
              &h, &c, &err) == 0);
    IN_C("onclick=\\\"alert(1)\\\"");
    free_run(h, c);

    /* unwrapped URL attributes fail at C-COMPILE time with a clear
     * type error pointing into the .thtml — check the shape */
    CHECK(run("component t(const char *u) {\n"
              "  <a href={ u }>x</a>\n"
              "}\n",
              &h, &c, &err) == 0);
    IN_C("tpl_attr_url(out, (u));"); /* const char* vs TplUrl */
    free_run(h, c);
}


static void expect_error(const char *src, const char *needle, size_t line)
{
    char *h = NULL;
    char *c = NULL;
    CtmplError err;
    CHECK(run(src, &h, &c, &err) == -1);
    CHECK_MSG(strstr(err.message, needle) != NULL, err.message);
    CHECK_MSG(err.line == line, err.message);
    free_run(h, c);
}

static void test_errors(void)
{
    /* stray brace in text */
    expect_error("component t(void) {\n"
                 "  <p>one two} three</p>\n"
                 "}\n",
                 "unexpected '}' in text", 2);

    /* else without a preceding if (else at a run start) */
    expect_error("component t(void) {\n"
                 "  <p>x</p>\n"
                 "  else { <p>y</p> }\n"
                 "}\n",
                 "no preceding 'if'", 3);

    /* reserved component names */
    expect_error("component raw(void) {\n"
                 "  <p>x</p>\n"
                 "}\n",
                 "collides with the runtime", 1);
    expect_error("component tpl_x(void) {\n"
                 "  <p>x</p>\n"
                 "}\n",
                 "collides with the runtime", 1);

    /* @raw misuse */
    expect_error("component t(void) {\n"
                 "  @raw\n"
                 "}\n",
                 "@raw expects exactly one argument", 2);
    expect_error("component t(const char *s) {\n"
                 "  @raw(s) { <p>block</p> }\n"
                 "}\n",
                 "@raw expects exactly one argument", 2);

    /* empty interpolation */
    expect_error("component t(void) {\n"
                 "  <p>{ }</p>\n"
                 "}\n",
                 "empty { } interpolation", 2);

    /* interpolation outside a quoted attribute value */
    expect_error("component t(const char *s) {\n"
                 "  <p { s }=\"x\">y</p>\n"
                 "}\n",
                 "interpolation outside a quoted attribute", 2);

    /* boolean attribute without a condition block */
    expect_error("component t(bool b) {\n"
                 "  <input checked?=b/>\n"
                 "}\n",
                 "expected '{' after '?='", 2);

    /* unterminated tag */
    expect_error("component t(void) {\n"
                 "  <p never closed\n"
                 "}\n",
                 "unterminated tag", 4);

    /* unterminated comment */
    expect_error("component t(void) {\n"
                 "  <!-- no end\n"
                 "}\n",
                 "unterminated <!-- comment", 4);

    /* unterminated component body */
    expect_error("component t(void) {\n"
                 "  <p>x</p>\n",
                 "missing '}'", 3);

    /* statement keyword as a text run start without a block */
    expect_error("component t(void) {\n"
                 "  <p>a</p>\n"
                 "  for a day\n"
                 "}\n",
                 "unbalanced", 4);

    /* no components at all (positionless: line 0) */
    expect_error("// just a comment\n", "no components found", 0);

    /* top level junk */
    expect_error("<p>markup</p>\n", "expected 'component'", 1);

    /* unterminated C string inside an expression */
    expect_error("component t(void) {\n"
                 "  { \"unterminated\n"
                 "}\n",
                 "unterminated string literal", 4);
}


static void test_html_validation_valid(void)
{
    char *h = NULL;
    char *c = NULL;
    CtmplError err;

    /* nested tags, void elements, self-closed void elements */
    CHECK(run("component t(void) {\n"
              "  <div><p>x</p><img src=\"a.png\"><hr/><br></div>\n"
              "}\n",
              &h, &c, &err) == 0);
    IN_C("<div><p>x</p><img src=\\\"a.png\\\"><hr/><br></div>");
    free_run(h, c);

    /* tag names are case-insensitive: <DIV> closes with </div> */
    CHECK(run("component t(void) {\n"
              "  <DIV>x</div>\n"
              "}\n",
              &h, &c, &err) == 0);
    free_run(h, c);

    /* tags inside HTML comments do not affect the stack */
    CHECK(run("component t(void) {\n"
              "  <!-- <div><p> never closed </div> -->\n"
              "  <p>ok</p>\n"
              "}\n",
              &h, &c, &err) == 0);
    free_run(h, c);

    /* tags spanning statement blocks are fine in parse order */
    CHECK(run("component t(bool b) {\n"
              "  <ul>\n"
              "  if b {\n"
              "    <li>yes</li>\n"
              "  } else {\n"
              "    <li>no</li>\n"
              "  }\n"
              "  </ul>\n"
              "}\n",
              &h, &c, &err) == 0);
    free_run(h, c);

    /* script/style participate: <script> opens, </script> closes */
    CHECK(run("component t(void) {\n"
              "  <script>var x = 1;</script>\n"
              "}\n",
              &h, &c, &err) == 0);
    free_run(h, c);
}

static void test_html_validation_errors(void)
{
    /* mismatched close: points at the open tag's line */
    expect_error("component t(void) {\n"
                 "  <div><p>x</div>\n"
                 "}\n",
                 "</div> closes nothing — expected </p>", 2);

    /* unclosed at component end: points at the opening '<' */
    expect_error("component t(void) {\n"
                 "  <div><p>x</p>\n"
                 "}\n",
                 "unclosed <div>", 2);

    /* close without any open tag */
    expect_error("component t(void) {\n"
                 "  </p>\n"
                 "}\n",
                 "</p> closes nothing — no tag is open", 2);

    /* non-void self-closing: browsers ignore the slash */
    expect_error("component t(void) {\n"
                 "  <div/>\n"
                 "}\n",
                 "non-void elements need a real closing tag", 2);

    /* void elements cannot have a closing tag */
    expect_error("component t(void) {\n"
                 "  <input></input>\n"
                 "}\n",
                 "void elements cannot have a closing tag", 2);

    /* empty closing tag name */
    expect_error("component t(void) {\n"
                 "  <p>x</>\n"
                 "}\n",
                 "empty closing tag name", 2);

    /* tags must be balanced WITHIN one component (the stack resets
     * per component — a close in a later component is an error) */
    expect_error("component a(void) {\n"
                 "  <p>x</p>\n"
                 "}\n"
                 "\n"
                 "component b(void) {\n"
                 "  </p>\n"
                 "}\n",
                 "no tag is open", 6);
}


static void test_golden_simple(void)
{
    static const char *src =
        "component greeting(const char *name) {\n"
        "  <div class=\"greeting\">Hello, { name }!</div>\n"
        "}\n";
    static const char *want_h =
        "/* Generated by ctmpl from test.thtml - DO NOT EDIT */\n"
        "#ifndef TEST_TEMPL_H\n"
        "#define TEST_TEMPL_H\n"
        "\n"
        "#include \"c_http_tpl.h\"\n"
        "\n"
        "void tpl_greeting(TplOut *out, const char *name);\n"
        "\n"
        "#endif /* TEST_TEMPL_H */\n";
    static const char *want_c =
        "/* Generated by ctmpl from test.thtml - DO NOT EDIT */\n"
        "#include \"test_templ.h\"\n"
        "\n"
        "void tpl_greeting(TplOut *out, const char *name)\n"
        "{\n"
        "#line 1 \"test.thtml\"\n"
        "    tpl_lit(out, \"\\n  <div class=\\\"greeting\\\">Hello, \");\n"
        "#line 2 \"test.thtml\"\n"
        "    tpl_esc(out, (name));\n"
        "    tpl_lit(out, \"!</div>\");\n"
        "}\n\n";

    char *h = NULL;
    char *c = NULL;
    CtmplError err;
    CHECK(run(src, &h, &c, &err) == 0);
    CHECK(h != NULL && strcmp(h, want_h) == 0);
    CHECK(c != NULL && strcmp(c, want_c) == 0);
    free_run(h, c);
}

static void test_golden_control_flow(void)
{
    static const char *src = "component t(const Page *p) {\n"
                             "  if p->count > 0 {\n"
                             "    <p>many</p>\n"
                             "  } else if p->count == 0 {\n"
                             "    <p>none</p>\n"
                             "  } else {\n"
                             "    <p>odd</p>\n"
                             "  }\n"
                             "}\n";
    char *h = NULL;
    char *c = NULL;
    CtmplError err;
    CHECK(run(src, &h, &c, &err) == 0);
    IN_C("if (p->count > 0) {");
    IN_C("} else if (p->count == 0) {");
    IN_C("} else {");
    IN_C("<p>many</p>");
    IN_C("<p>none</p>");
    IN_C("<p>odd</p>");
    IN_H("void tpl_t(TplOut *out, const Page *p);");
    free_run(h, c);
}

